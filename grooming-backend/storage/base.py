"""The storage interface. Routes and services only ever talk to this.

To add a database: write one adapter that implements Store and register it
in storage/__init__.py. IDs and seq numbers are generated by the app, never
by the database, and no queries are written outside adapters.
"""

from abc import ABC, abstractmethod
from typing import Optional

from schemas import Alert, Analysis, Contact, Message, PushSubscription


class Store(ABC):
    # contacts
    @abstractmethod
    def add_contact(self, contact: Contact) -> Contact: ...

    @abstractmethod
    def list_contacts(self) -> list[Contact]: ...

    @abstractmethod
    def get_contact(self, contact_id: str) -> Optional[Contact]: ...

    # messages
    @abstractmethod
    def add_message(self, message: Message) -> Message: ...

    @abstractmethod
    def list_messages(
        self, contact_id: Optional[str] = None, after: Optional[int] = None
    ) -> list[Message]:
        """Messages ordered by seq, optionally for one contact and seq > after."""

    @abstractmethod
    def max_seq(self) -> int:
        """Highest stored seq (0 if empty); used to seed the app's counter."""

    # analysis
    @abstractmethod
    def save_analysis(self, analysis: Analysis) -> Analysis: ...

    @abstractmethod
    def get_analyses(self, message_ids: list[str]) -> dict[str, Analysis]: ...

    # alerts
    @abstractmethod
    def add_alert(self, alert: Alert) -> Alert: ...

    @abstractmethod
    def list_alerts(self) -> list[Alert]:
        """Newest first."""

    @abstractmethod
    def acknowledge_alert(self, alert_id: str) -> Optional[Alert]: ...

    # push subscriptions
    @abstractmethod
    def save_subscription(self, sub: PushSubscription) -> PushSubscription:
        """Insert, or replace an existing row with the same endpoint."""

    @abstractmethod
    def list_subscriptions(self) -> list[PushSubscription]: ...

    @abstractmethod
    def delete_subscription(self, endpoint: str) -> None:
        """Remove a subscription the push service reported as gone."""

    def close(self) -> None:
        pass
